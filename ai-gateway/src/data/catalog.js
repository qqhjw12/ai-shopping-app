/** 从长描述里摘一句最有信息量的话作为「一句话卖点」 */
function deriveHighlight(desc) {
  const first = String(desc).split(/[，,。；;]/).map((s) => s.trim()).filter(Boolean)[0] || String(desc);
  if (first.length <= 22) return first;
  // 优先取含数字的那句（参数最像卖点），否则截断
  const withNum = String(desc).split(/[，,。；;]/).find((s) => /\d/.test(s) && s.length <= 26);
  return (withNum || first).slice(0, 24);
}

export function buildCatalog() {
  const products = [];
  const skus = [];
  // 子类目归属表：用于第 10 个字段缺失/写错时的兜底（保证数据永远自洽）
  const VALID_SUBS = SUBCATEGORIES.reduce((acc, s) => {
    acc[s.id] = s.parentId;
    return acc;
  }, {});
  // 每个类目轮询游标，兜底分配时均摊到各子类目
  const roundRobin = {};
  const pickSub = (categoryId, idx) => {
    const subs = SUBS_BY_CATEGORY[categoryId] || [];
    if (!subs.length) return null;
    roundRobin[categoryId] = ((roundRobin[categoryId] ?? -1) + 1) % subs.length;
    return subs[subs.length === 1 ? 0 : idx === undefined ? roundRobin[categoryId] : Math.min(idx, subs.length - 1)].id;
  };

  RAW.forEach(([id, name, brand, categoryId, price, originalPrice, tags, desc, specStr, rawSub], idx) => {
    const specs = specStr.split('|');
    const reviews = 60 + hashInt(id + 'r', 2800);
    const rating = Number((4.4 + hashInt(id + 'g', 60) / 100).toFixed(1));
    const sales = 120 + hashInt(id + 's', 18000);
    const baseHue = CATEGORY_HUE[categoryId] ?? 210;
    const hueShift = hashInt(id + 'c', 27) - 13; // -13..13
    const tagList = tags.split(',').map((t) => t.trim()).filter(Boolean);
    // 子类目：只在「该子类目确实属于本类目」时采用，否则按类目下属二级类目轮转兜底
    const subCategoryId = VALID_SUBS[rawSub] === categoryId ? rawSub : pickSub(categoryId);
    products.push({
      id,
      name,
      brand,
      categoryId,
      price,
      originalPrice,
      description: desc,
      tags: tagList,
      rating: Math.min(5, rating),
      reviewsCount: reviews,
      sales,
      status: 'on_sale',
      sort: idx,
      subCategoryId,
      // 视觉：双色渐变封面（前端用它渲染程序化商品图）
      coverColor: `${hslToHex(baseHue + hueShift, 68, 52)},${hslToHex(baseHue + hueShift + 26, 74, 66)}`,
      highlight: deriveHighlight(desc),
      highlights: CATEGORY_PROMISES[categoryId] || DEFAULT_PROMISES,
    });
    specs.forEach((spec, i) => {
      skus.push({
        id: `${id}-s${i + 1}`,
        productId: id,
        spec: spec.trim(),
        // 高配版按阶梯加价，最低配即标价
        price: i === 0 ? price : price + i * 300,
        stock: 5 + hashInt(`${id}-${i}`, 180),
        status: 'on_sale',
      });
    });
  });
  return { products, skus };
}

