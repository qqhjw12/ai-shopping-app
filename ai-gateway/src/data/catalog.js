// 确定性伪随机（同一商品每次生成一致，避免重启后评分/销量乱跳）
function hashInt(str, mod) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h) % mod;
}

